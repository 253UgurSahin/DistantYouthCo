// Copies the Lucide icons the app uses (ISC licence) into frontend/js/icons.js as inner SVG markup.
// Run again after adding a name: node scripts/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const NAMES = ['play', 'pause', 'skip-back', 'skip-forward', 'shuffle', 'repeat', 'search', 'plus', 'x',
  'chevron-right', 'chevron-left', 'chevron-down', 'download', 'upload', 'copy', 'check', 'maximize', 'list-music',
  'message-square-text', 'video', 'volume-2', 'volume-x', 'moon', 'sun', 'monitor', 'log-out', 'settings',
  'users', 'trash-2', 'pencil', 'folder', 'list', 'external-link', 'arrow-up', 'arrow-down', 'image',
  'file-audio', 'refresh-cw', 'loader-circle', 'music', 'ellipsis', 'eye-off', 'key-round', 'circle-alert',
  'eye', 'archive', 'clapperboard', 'circle-check', 'list-todo'];
const dir = path.resolve('node_modules/lucide-static/icons');
const out = {};
for (const n of NAMES) {
  const svg = fs.readFileSync(path.join(dir, `${n}.svg`), 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}
fs.writeFileSync('frontend/js/icons.js',
  `// Lucide icons (ISC licence, see /icons/LICENSE). Generated by scripts/build-icons.mjs.\nexport const ICONS = ${JSON.stringify(out, null, 1)};\n`);
fs.copyFileSync('node_modules/lucide-static/LICENSE', 'frontend/icons/LICENSE');
console.log(`${NAMES.length} icons written`);
